// ===== دالة الرسم الرئيسية =====
function drawSprite(ctx, sprite, x, y, scale) {
  scale = scale || 1;
  for (var row = 0; row < sprite.length; row++) {
    var line = sprite[row];
    for (var col = 0; col < line.length; col++) {
      var ch = line[col];
      var color = PALETTE[ch];
      if (color) {
        ctx.fillStyle = color;
        ctx.fillRect(
          Math.floor(x + col * scale),
          Math.floor(y + row * scale),
          scale, scale
        );
      }
    }
  }
}

// دالة ترجع أبعاد السبريت
function spriteSize(sprite, scale) {
  scale = scale || 1;
  var w = 0;
  for (var i = 0; i < sprite.length; i++) {
    if (sprite[i].length > w) w = sprite[i].length;
  }
  return { w: w * scale, h: sprite.length * scale };
}
